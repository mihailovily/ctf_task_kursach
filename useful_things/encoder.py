to_encode = input()

# + => %
# - => ?
# [ => )
# ] => (
# . => :

to_encode = "+[----->+++<]>+.++++++++++++..----.+++.+[-->+<]>.-----------..[--->+<]>++.++.+++++++++++.------------.[--->+<]>---.+[->+++<]>.[-->+<]>---.--[--->+<]>-.++++++++++++.--.+++[->+++++<]>-.+[----->+<]>---.----.-.-------.++++++++.+++.+++.+++++++.[------>+<]>.+++.-[--->+<]>.-[----->++<]>-.++[->++<]>+.-[--->+<]>--.+++[->+++<]>+.-------.+++++++.+++++++++.+++.+++[->+++<]>.-[->++++<]>+.----------.++++++.-[++>---<]>+.-[--->++<]>.--.-------------..[->+++<]>.+[----->+<]>---.------------.++++++++.+++++."
encoded = ''
for i in to_encode:
    if i == '-':
        encoded += '?'
    elif i == '+':
        encoded += '&'
    elif i == '[':
        encoded += ')'
    elif i == ']':
        encoded += '('
    elif i == '.':
        encoded += ':'
    elif i == '>':
        encoded += '~'
    elif i == '<':
        encoded += ';'
    else:
        encoded += i
        

print(encoded)